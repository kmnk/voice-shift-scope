export type Key = keyof (typeof dict)["en"];

let current: Lang = "en";

export function lang(): Lang {
  return current;
}

export function setLang(l: Lang): void {
  current = l;
  document.documentElement.lang = l;
}

export function t(key: Key, params: Record<string, string | number> = {}): string {
  let s: string = dict[current][key] ?? dict.en[key] ?? key;
  for (const [k, v] of Object.entries(params)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

export function hasKey(key: string): key is Key {
  return key in dict.en;
}

/// Rewrites elements with data-i18n (text), data-i18n-title (tooltip), and data-i18n-aria (accessible name) in the current language.
export function applyStatic(root: ParentNode = document): void {
  root.querySelectorAll<HTMLElement>("[data-i18n]").forEach((el) => {
    const key = el.dataset.i18n!;
    if (hasKey(key)) el.textContent = t(key);
  });
  root.querySelectorAll<HTMLElement>("[data-i18n-title]").forEach((el) => {
    const key = el.dataset.i18nTitle!;
    if (hasKey(key)) el.title = t(key);
  });
  root.querySelectorAll<HTMLElement>("[data-i18n-aria]").forEach((el) => {
    const key = el.dataset.i18nAria!;
    if (hasKey(key)) el.setAttribute("aria-label", t(key));
  });
}

